#[cfg(test)]
mod tests {
    use super::TABLE;

    #[test]
    fn entries_are_clean() {
        for (cmd, subs) in TABLE {
            assert!(!subs.is_empty(), "{cmd}");
            let mut seen = std::collections::HashSet::new();
            for s in *subs {
                assert!(
                    s.chars()
                        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'),
                    "{cmd} {s}"
                );
                assert!(seen.insert(*s), "duplicate {cmd} {s}");
            }
        }
        let git = TABLE
            .iter()
            .find(|(c, _)| *c == "git")
            .map_or(&[][..], |(_, s)| *s);
        assert!(git.contains(&"commit") && git.contains(&"status"));
    }
}
